#[derive(Debug)]
struct StagingFile {
    path: PathBuf,
    armed: bool,
}

#[derive(Debug)]
struct ProcessGroupGuard {
    raw_pid: Option<i32>,
}

impl ProcessGroupGuard {
    fn new(child: &tokio::process::Child) -> Self {
        Self {
            raw_pid: child.id().and_then(|pid| i32::try_from(pid).ok()),
        }
    }

    fn disarm(&mut self) {
        self.raw_pid = None;
    }
}

impl Drop for ProcessGroupGuard {
    fn drop(&mut self) {
        let Some(pid) = self.raw_pid.and_then(rustix::process::Pid::from_raw) else {
            return;
        };
        let _ = rustix::process::kill_process_group(pid, rustix::process::Signal::KILL);
    }
}

impl StagingFile {
    fn new(path: PathBuf) -> Self {
        Self { path, armed: true }
    }

    fn path(&self) -> &Path {
        &self.path
    }

    fn disarm(&mut self) {
        self.armed = false;
    }

    async fn remove(&mut self) -> Result<(), AdapterError> {
        match tokio::fs::remove_file(&self.path).await {
            Ok(()) => {
                self.disarm();
                Ok(())
            }
            Err(error) if error.kind() == io::ErrorKind::NotFound => {
                self.disarm();
                Ok(())
            }
            Err(error) => Err(AdapterError::Io(error)),
        }
    }
}

impl Drop for StagingFile {
    fn drop(&mut self) {
        if self.armed {
            let _ = std::fs::remove_file(&self.path);
        }
    }
}

fn validate_config_candidate(candidate: &str) -> Result<(), AdapterError> {
    if candidate.contains('\r') || candidate.contains('\0') || !candidate.ends_with('\n') {
        return Err(AdapterError::InvalidRequest);
    }
    let mut lines = candidate.lines();
    if lines.next() != Some("# generated by ocservia config-plan/v1") {
        return Err(AdapterError::InvalidRequest);
    }
    let mut seen = HashSet::new();
    for line in lines {
        let (name, value) = line.split_once(" = ").ok_or(AdapterError::InvalidRequest)?;
        if !CONFIG_DIRECTIVES.contains(&name)
            || !seen.insert(name)
            || value.is_empty()
            || value.len() > 4096
        {
            return Err(AdapterError::InvalidRequest);
        }
        if value.contains("{{") || value.contains("}}") || value.contains("../") {
            return Err(AdapterError::InvalidRequest);
        }
        let secret = parse_secret_placeholder(value);
        if value.contains("${") && secret.is_none() {
            return Err(AdapterError::InvalidRequest);
        }
        if secret.is_some() && !matches!(name, "server-key" | "server-cert" | "ca-cert") {
            return Err(AdapterError::InvalidRequest);
        }
        match name {
            "server-key" | "server-cert" | "ca-cert" if secret.is_none() => {
                return Err(AdapterError::InvalidRequest);
            }
            "socket-file" if value != "/run/ocserv.socket" => {
                return Err(AdapterError::InvalidRequest);
            }
            "auth" if value != "plain[passwd=/etc/ocserv/ocpasswd]" => {
                return Err(AdapterError::InvalidRequest);
            }
            _ => {}
        }
    }
    if seen.is_empty() {
        return Err(AdapterError::InvalidRequest);
    }
    Ok(())
}

fn parse_secret_placeholder(value: &str) -> Option<&str> {
    let body = value.strip_prefix("${secret:")?.strip_suffix('}')?;
    let (provider, key) = body.split_once(':')?;
    if provider.is_empty()
        || key.is_empty()
        || key.contains("..")
        || !provider.bytes().all(valid_label_byte)
        || !key.bytes().all(valid_secret_key_byte)
    {
        return None;
    }
    Some(provider)
}

fn valid_label_byte(value: u8) -> bool {
    value.is_ascii_alphanumeric() || matches!(value, b'.' | b'_' | b'-')
}
fn valid_secret_key_byte(value: u8) -> bool {
    valid_label_byte(value) || value == b'/'
}

fn redacted_candidate_diff(candidate: &str) -> Result<String, AdapterError> {
    let mut output = String::from("- <current configuration redacted>\n");
    for line in candidate.lines() {
        if line.starts_with('#') {
            continue;
        }
        let (name, value) = line.split_once(" = ").ok_or(AdapterError::InvalidRequest)?;
        let safe = parse_secret_placeholder(value).map_or(value.to_owned(), |provider| {
            format!("<secret-ref:{provider}>")
        });
        output.push_str("+ ");
        output.push_str(name);
        output.push_str(" = ");
        output.push_str(&safe);
        output.push('\n');
    }
    if output.len() > MAX_CONFIG_PLAN_BYTES {
        return Err(AdapterError::OutputLimit);
    }
    Ok(output)
}

fn parser_candidate(candidate: &str) -> Result<(Vec<u8>, bool), AdapterError> {
    let mut output = String::from("# generated by ocservia config-plan/v1\n");
    let mut unresolved = false;
    for line in candidate.lines().skip(1) {
        let (_, value) = line.split_once(" = ").ok_or(AdapterError::InvalidRequest)?;
        if parse_secret_placeholder(value).is_some() {
            unresolved = true;
            continue;
        }
        output.push_str(line);
        output.push('\n');
    }
    Ok((output.into_bytes(), unresolved))
}

/// Root-controlled fixed local resources used by the adapter.
#[derive(Clone, Debug)]
pub struct FixedResources {
    systemctl: PathBuf,
    ocserv: PathBuf,
    occtl: PathBuf,
    config: PathBuf,
    boot_id: PathBuf,
    ocpasswd: PathBuf,
    user_file: PathBuf,
    openssl: PathBuf,
    secret_key: PathBuf,
    secret_key_id: String,
    effect_store: PathBuf,
    effect_store_key: PathBuf,
}

impl Default for FixedResources {
    fn default() -> Self {
        Self {
            systemctl: PathBuf::from("/usr/bin/systemctl"),
            ocserv: PathBuf::from("/usr/sbin/ocserv"),
            occtl: PathBuf::from("/usr/bin/occtl"),
            config: PathBuf::from("/etc/ocserv/ocserv.conf"),
            boot_id: PathBuf::from("/proc/sys/kernel/random/boot_id"),
            ocpasswd: PathBuf::from("/usr/bin/ocpasswd"),
            user_file: PathBuf::from("/etc/ocserv/ocpasswd"),
            openssl: PathBuf::from("/usr/bin/openssl"),
            secret_key: PathBuf::from("/etc/ocservia/password-seal-private.pem"),
            secret_key_id: String::from("default"),
            effect_store: PathBuf::from("/var/lib/ocservia-privd/desired-effects.sqlite3"),
            effect_store_key: PathBuf::from("/var/lib/ocservia-privd/desired-effects.key"),
        }
    }
}

impl FixedResources {
    /// Constructs resources from trusted process-startup configuration.
    ///
    /// These values are never populated from an Agent RPC.
    ///
    /// # Errors
    ///
    /// Rejects non-absolute paths.
    pub fn new(
        systemctl: PathBuf,
        ocserv: PathBuf,
        occtl: PathBuf,
        config: PathBuf,
        boot_id: PathBuf,
    ) -> Result<Self, AdapterError> {
        for path in [&systemctl, &ocserv, &occtl, &config, &boot_id] {
            if !path.is_absolute() {
                return Err(AdapterError::InvalidResource);
            }
        }
        Ok(Self {
            systemctl,
            ocserv,
            occtl,
            config,
            boot_id,
            ..Self::default()
        })
    }

    /// Overrides only fixed root-owned user resources at process startup.
    ///
    /// # Errors
    ///
    /// Rejects non-absolute paths and invalid configured key identifiers.
    pub fn with_user_resources(
        mut self,
        ocpasswd: PathBuf,
        user_file: PathBuf,
        openssl: PathBuf,
        secret_key: PathBuf,
        secret_key_id: String,
    ) -> Result<Self, AdapterError> {
        for path in [&ocpasswd, &user_file, &openssl, &secret_key] {
            if !path.is_absolute() {
                return Err(AdapterError::InvalidResource);
            }
        }
        if !valid_key_id(&secret_key_id) {
            return Err(AdapterError::InvalidResource);
        }
        self.ocpasswd = ocpasswd;
        self.user_file = user_file;
        self.openssl = openssl;
        self.secret_key = secret_key;
        self.secret_key_id = secret_key_id;
        Ok(self)
    }

    /// Overrides the fixed root-owned reconciliation store for isolated deployments or tests.
    ///
    /// # Errors
    ///
    /// Rejects non-absolute paths or colocated database and key files.
    pub fn with_effect_store(
        mut self,
        effect_store: PathBuf,
        effect_store_key: PathBuf,
    ) -> Result<Self, AdapterError> {
        if !effect_store.is_absolute()
            || !effect_store_key.is_absolute()
            || effect_store == effect_store_key
        {
            return Err(AdapterError::InvalidResource);
        }
        self.effect_store = effect_store;
        self.effect_store_key = effect_store_key;
        Ok(self)
    }
}

/// Non-secret controller command identity bound into desired-effect evidence.
#[derive(Clone, Copy, Debug)]
pub struct EffectIdentity<'a> {
    /// Stable controller command UUID bytes.
    pub command_id: &'a [u8],
    /// Stable idempotency UUID bytes.
    pub idempotency_key: &'a [u8],
    /// Canonical semantic payload SHA-256.
    pub semantic_payload_sha256: &'a [u8],
    /// Command expiry after which evidence may be safely garbage-collected.
    pub expires_at_unix_seconds: i64,
}

/// Adapter execution limits.
#[derive(Clone, Copy, Debug)]
pub struct Limits {
    /// Maximum child execution time.
    pub timeout: Duration,
    /// Maximum retained bytes per stdout/stderr stream.
    pub output_bytes: usize,
}

impl Default for Limits {
    fn default() -> Self {
        Self {
            timeout: Duration::from_secs(5),
            output_bytes: DEFAULT_OUTPUT_BYTES,
        }
    }
}

